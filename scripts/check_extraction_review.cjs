const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const assert = require('assert');
(async () => {
  const browser = await chromium.launch({headless:true,channel:'chrome'});
  const page = await browser.newPage({viewport:{width:1440,height:960}});
  const errors=[], requests=[];
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('request',r=>requests.push(r.url()));
  await page.goto('file://'+path.resolve('output/extraction_review_v1/index.html'));
  assert.equal(await page.locator('#results > tr:not(.detail)').count(),50);
  assert.equal(await page.locator('#results > tr:not(.detail) .badge').count(),250);
  await page.locator('#filter').selectOption('zero_amount');
  assert.equal(await page.locator('#results > tr:not(.detail)').count(),33);
  await page.locator('#filter').selectOption('possible_source_truncation');
  assert.equal(await page.locator('#results > tr:not(.detail)').count(),11);
  await page.locator('#filter').selectOption('mismatch');
  assert.match(await page.locator('#results').innerText(),/No hay oportunidades/);
  await page.locator('#reset').click();
  await page.locator('#search').fill('ocds-dgv273-seacev3-2025-2543-904');
  assert.equal(await page.locator('#results > tr:not(.detail)').count(),1);
  await page.locator('#reset').click();
  await page.locator('button[aria-controls="detail-1"]').click();
  assert.equal(await page.locator('#detail-1').isVisible(),true);
  assert.match(await page.locator('#detail-1').innerText(),/Referencia automática/);
  assert.equal(await page.locator('#detail-1 a').getAttribute('rel'),'noopener noreferrer');
  await page.locator('button[aria-controls="detail-1"]').click();
  assert.equal(await page.locator('#detail-1').isVisible(),false);
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#download').click();
  const download=await downloadPromise;
  const downloaded=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
  assert.equal(downloaded.opportunities.length,50);
  assert.equal(downloaded.summary.human_judgments_completed,0);
  assert.equal(downloaded.summary.metrics_by_field.experience.f1,null);
  fs.mkdirSync('output/review_checks',{recursive:true});
  await page.screenshot({path:'output/review_checks/desktop.png',fullPage:true});
  await page.screenshot({path:'output/review_checks/desktop-top.png'});
  await page.locator('button[aria-controls="detail-1"]').click();
  await page.locator('#detail-1').screenshot({path:'output/review_checks/evidence.png'});
  await page.locator('button[aria-controls="detail-1"]').click();
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.waitForTimeout(250);
  await page.screenshot({path:'output/review_checks/mobile-top.png'});
  await page.screenshot({path:'output/review_checks/mobile.png',fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert.equal(overflow,false);
  assert.deepEqual(errors,[]);
  assert.equal(requests.filter(u=>!u.startsWith('file:')&&!u.startsWith('blob:')).length,0);
  const report={passed:true,rows:50,fields:250,zero_amount_filter:33,truncation_filter:11,search:true,empty_state:true,source_expansion:true,json_download:true,offline:true,page_overflow:false,page_errors:errors,viewports:[1440,390]};
  fs.writeFileSync('output/review_checks/functional.json',JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
